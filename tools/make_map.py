#!/usr/bin/env python3
"""Generate SoulCage/map_data.h: border outlines and towns around the pendant's home.

Borders come from MeteoPlaneRadar's EuMapData.h (github.com/petus/MeteoPlaneRadar, MIT),
which itself is Natural Earth 1:10m (public domain); its cities are GeoNames (CC BY 4.0).
Only a window around Central Europe is kept, plus a hand-made list of local towns
around Jablonec nad Nisou with proper Czech names (our font has diacritics).

Usage: python3 tools/make_map.py path/to/EuMapData.h
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAT0, LAT1, LON0, LON1 = 48.3, 52.4, 11.5, 19.2   # kept window
SCALE, LON_O, LAT_O = 0.0011, -32.0, 34.0

# Local places (name, lat, lon, tier 1 = always .. 3 = only when zoomed in)
LOCAL = [
    ("Jablonec n. N.", 50.7243, 15.1711, 1), ("Liberec", 50.7663, 15.0543, 1), ("Turnov", 50.5874, 15.1569, 2),
    ("Železný Brod", 50.6427, 15.2541, 2), ("Tanvald", 50.7374, 15.3059, 2), ("Semily", 50.6020, 15.3356, 2),
    ("Mnichovo Hradiště", 50.5272, 14.9711, 3), ("Mladá Boleslav", 50.4113, 14.9032, 1), ("Jičín", 50.4373, 15.3517, 2),
    ("Český Dub", 50.6600, 14.9963, 3), ("Hodkovice", 50.6659, 15.0899, 3), ("Frýdlant", 50.9214, 15.0797, 2),
    ("Česká Lípa", 50.6855, 14.5376, 2), ("Trutnov", 50.5610, 15.9127, 2), ("Harrachov", 50.7722, 15.4310, 3),
    ("Jilemnice", 50.6090, 15.5066, 3), ("Nová Paka", 50.4945, 15.5151, 3), ("Praha", 50.0755, 14.4378, 1),
    ("Hradec Králové", 50.2092, 15.8328, 1), ("Ústí n. L.", 50.6607, 14.0323, 1), ("Zittau", 50.8962, 14.8075, 2),
    ("Görlitz", 51.1528, 14.9872, 2), ("Jelenia Góra", 50.9044, 15.7194, 2), ("Sněžka", 50.7360, 15.7398, 2),
    ("Ještěd", 50.7325, 14.9847, 2), ("Kokonín", 50.6977, 15.1838, 3), ("Rychnov u J.", 50.6782, 15.1527, 3),
    ("Malá Skála", 50.6418, 15.1941, 3),
]


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    pts = [(int(a), int(b)) for a, b in re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}", src.split("EU_RING_OFFSETS")[0])]
    offs = [int(v) for v in re.search(r"EU_RING_OFFSETS\[\d+\] = \{(.*?)\};", src, re.S).group(1).replace("\n", "").split(",") if v.strip()]
    rings = []
    for r in range(len(offs) - 1):
        ring = pts[offs[r]:offs[r + 1]]
        lons = [LON_O + x * SCALE for x, _ in ring]
        lats = [LAT_O + y * SCALE for _, y in ring]
        if not ring or max(lons) < LON0 or min(lons) > LON1 or max(lats) < LAT0 or min(lats) > LAT1:
            continue
        # keep only the part of the ring inside the window (plus one point either side)
        keep = [i for i, (lo, la) in enumerate(zip(lons, lats)) if LON0 <= lo <= LON1 and LAT0 <= la <= LAT1]
        if not keep:
            continue
        runs, run = [], [keep[0]]
        for i in keep[1:]:
            if i == run[-1] + 1:
                run.append(i)
            else:
                runs.append(run)
                run = [i]
        runs.append(run)
        for run in runs:
            a, b = max(run[0] - 1, 0), min(run[-1] + 1, len(ring) - 1)
            rings.append([(lats[i], lons[i]) for i in range(a, b + 1)])
    out = ["// Generated by tools/make_map.py - do not edit by hand.",
           "// Borders: Natural Earth 1:10m (public domain) via MeteoPlaneRadar (MIT, chiptron.cz).",
           "#pragma once", "#include <stdint.h>", "",
           "struct MapTown { const char *name; float lat, lon; uint8_t tier; };", ""]
    flat, starts = [], [0]
    for ring in rings:
        for la, lo in ring:
            # origin 1 degree outside the window, 0.0002 deg (~20 m) steps
            flat.append((min(max(round((la - LAT0 + 1) / 0.0002), 0), 65535),
                         min(max(round((lo - LON0 + 1) / 0.0002), 0), 65535)))
        starts.append(len(flat))
    out.append(f"#define MAP_LAT0 {LAT0 - 1}f\n#define MAP_LON0 {LON0 - 1}f\n#define MAP_STEP 0.0002f")
    out.append(f"static const uint16_t MAP_PTS[{len(flat)}][2] = {{")
    for i in range(0, len(flat), 8):
        out.append("  " + ",".join(f"{{{a},{b}}}" for a, b in flat[i:i + 8]) + ",")
    out.append("};")
    out.append(f"static const uint16_t MAP_RINGS[{len(starts)}] = {{{','.join(map(str, starts))}}};")
    out.append(f"#define MAP_RING_COUNT {len(starts) - 1}")
    out.append(f"static const MapTown MAP_TOWNS[] = {{")
    for name, la, lo, tier in LOCAL:
        out.append(f'  {{"{name}", {la}f, {lo}f, {tier}}},')
    out.append("};")
    open(os.path.join(ROOT, "SoulCage", "map_data.h"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"rings {len(rings)}, points {len(flat)}, towns {len(LOCAL)}")


if __name__ == "__main__":
    main()
