#!/usr/bin/env python3
"""Generate SoulCage/font_data.h: anti-aliased bitmap fonts with Czech letters.

Glyphs are 4-bit alpha, two pixels per byte, rows padded to whole bytes.
Fonts: Inter (SIL Open Font License 1.1, https://rsms.me/inter/).
Usage: python3 tools/make_font.py [path/to/fonts]
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"
CHARS = sorted(set(chr(c) for c in range(32, 127)) | set("áčďéěíňóřšťúůýžÁČĎÉĚÍŇÓŘŠŤÚŮÝŽ°…–’"))
FONTS = [  # (C name, file, size)
    ("TINY", "Inter-Medium.otf", 12),
    ("SMALL", "Inter-SemiBold.otf", 17),
    ("BIG", "InterDisplay-ExtraBold.otf", 30),
]


def build(cname, file, size):
    font = ImageFont.truetype(os.path.join(FONT_DIR, file), size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in CHARS:
        advance = round(font.getlength(ch))
        box = font.getbbox(ch, anchor="ls")
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
            px = img.tobytes()
            for y in range(h):
                row = px[y * w:(y + 1) * w]
                for x in range(0, w, 2):
                    a = row[x] >> 4
                    b = (row[x + 1] >> 4) if x + 1 < w else 0
                    data.append(a << 4 | b)
        glyphs.append((ord(ch), w, h, box[0], box[1], advance, offset))
    lines = [f"static const FontGlyph FONT_{cname}_GLYPHS[] = {{"]
    for g in glyphs:
        lines.append("  {%d, %d, %d, %d, %d, %d, %d}," % g)
    lines.append("};")
    lines.append(f"static const uint8_t FONT_{cname}_BITMAP[] = {{")
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const FontData FONT_{cname}_DATA = {{FONT_{cname}_GLYPHS, {len(glyphs)}, "
                 f"FONT_{cname}_BITMAP, {ascent + descent}, {ascent}}};")
    return "\n".join(lines), len(data)


def main():
    out = ["// Generated by tools/make_font.py - do not edit by hand.",
           "// Inter font (SIL Open Font License 1.1), rasterised to 4-bit alpha.",
           "#pragma once", "#include \"gfx.h\"", ""]
    for cname, file, size in FONTS:
        text, n = build(cname, file, size)
        out.append(text)
        out.append("")
        print(f"{cname}: {size}px, {n} bytes")
    with open(os.path.join(ROOT, "SoulCage", "font_data.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
