#!/usr/bin/env python3
"""Generate SoulCage/anim_data.h from animation sources.

Every frame is a 240x240 RGB565 image stored big-endian (the byte order the
GC9A01 expects on the wire) and compressed with zlib. The firmware inflates a
frame straight into the frame buffer with the ROM inflater of the ESP32-S3,
so the 15 MB of raw frames of the original project shrink to ~2.4 MB and two
OTA slots fit into the 16 MB flash.

Sources are listed in tools/animations.json. A source can be:
  * an original SoulCage image header (*.h with `*_allArray`)
  * an animated GIF (needs Pillow)
  * a directory with PNG/JPG frames sorted by name (needs Pillow)

Usage: python3 tools/convert_animations.py [--config tools/animations.json]
"""
import argparse
import json
import os
import re
import struct
import sys
import zlib

W = H = 240
FRAME_PIXELS = W * H


def frames_from_header(path):
    text = open(path, encoding="utf-8").read()
    arrays = dict(re.findall(r"const uint16_t (\w+) \[\] PROGMEM = \{(.*?)\};", text, re.S))
    order = re.search(r"allArray\[\d+\] = \{(.*?)\};", text, re.S).group(1)
    for name in (o.strip() for o in order.split(",")):
        if not name:
            continue
        pixels = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", arrays[name])]
        if len(pixels) != FRAME_PIXELS:
            sys.exit(f"{path}: frame {name} has {len(pixels)} pixels, expected {FRAME_PIXELS}")
        yield pixels


def rgb565(img):
    img = img.convert("RGB")
    if img.size != (W, H):
        img = img.resize((W, H))
    data = img.tobytes()
    return [((data[i] & 0xF8) << 8) | ((data[i + 1] & 0xFC) << 3) | (data[i + 2] >> 3)
            for i in range(0, len(data), 3)]


def frames_from_images(path):
    from PIL import Image, ImageSequence

    if os.path.isdir(path):
        for name in sorted(os.listdir(path)):
            if name.lower().endswith((".png", ".jpg", ".jpeg", ".bmp")):
                yield rgb565(Image.open(os.path.join(path, name)))
    else:
        for frame in ImageSequence.Iterator(Image.open(path)):
            yield rgb565(frame)


def load_frames(path):
    if path.endswith(".h"):
        return list(frames_from_header(path))
    return list(frames_from_images(path))


def c_bytes(data, indent="  "):
    lines = []
    for i in range(0, len(data), 24):
        lines.append(indent + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    return "\n".join(lines)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=os.path.join(root, "tools", "animations.json"))
    ap.add_argument("--out", default=os.path.join(root, "SoulCage", "anim_data.h"))
    args = ap.parse_args()

    config = json.load(open(args.config, encoding="utf-8"))
    base = os.path.dirname(os.path.abspath(args.config))
    out = [
        "// Generated by tools/convert_animations.py - do not edit by hand.",
        "// Frames: 240x240 RGB565 big-endian, each frame a separate zlib stream.",
        "#pragma once",
        "#include \"animations.h\"",
        "",
    ]
    table = []
    raw_total = packed_total = 0
    for anim in config["animations"]:
        ident = anim["id"]
        frames = load_frames(os.path.join(base, anim["source"]))
        blob = bytearray()
        offsets = [0]
        for pixels in frames:
            packed = zlib.compress(struct.pack(f">{FRAME_PIXELS}H", *pixels), 9)
            blob += packed
            offsets.append(len(blob))
        raw_total += len(frames) * FRAME_PIXELS * 2
        packed_total += len(blob)
        out.append(f"static const uint8_t anim_{ident}_data[] = {{")
        out.append(c_bytes(blob))
        out.append("};")
        out.append(f"static const uint32_t anim_{ident}_offsets[] = {{{','.join(map(str, offsets))}}};")
        out.append("")
        table.append((anim, len(frames)))
        print(f"{ident}: {len(frames)} frames, {len(blob)} bytes")

    out.append("static const Animation kAnimations[] = {")
    for anim, count in table:
        out.append(
            f"  {{\"{anim['id']}\", \"{anim['name']}\", anim_{anim['id']}_data, "
            f"anim_{anim['id']}_offsets, {count}, {str(anim.get('soul', True)).lower()}}},"
        )
    out.append("};")
    out.append("")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"total: {raw_total} -> {packed_total} bytes ({packed_total * 100 // raw_total} %)")


if __name__ == "__main__":
    main()
