#!/usr/bin/env python3
"""Generate SoulCage/web_icon.h (home-screen icon for the iPhone) from assets/icon_panda.png.

assets/icon_panda.png is a frame rendered by tools/preview (ghost renderer)."""
import io
import os
from PIL import Image, ImageDraw

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
frame = Image.open(os.path.join(root, "assets", "icon_panda.png")).convert("RGB")
size = 180
icon = Image.new("RGB", (size, size), (11, 11, 16))
face = frame.resize((size - 16, size - 16), Image.LANCZOS)
mask = Image.new("L", face.size, 0)
ImageDraw.Draw(mask).ellipse((0, 0, face.size[0] - 1, face.size[1] - 1), fill=255)
icon.paste(face, (8, 8), mask)
buf = io.BytesIO()
icon.save(buf, "PNG", optimize=True)
data = buf.getvalue()
lines = ["// Generated by tools/make_icon.py", "#pragma once", "#include <stdint.h>",
         "static const uint8_t WEB_ICON_PNG[] = {"]
for i in range(0, len(data), 24):
    lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
lines.append("};")
open(os.path.join(root, "SoulCage", "web_icon.h"), "w").write("\n".join(lines) + "\n")
print(f"icon: {len(data)} bytes")
